#!/usr/bin/env node
/**
 * Embeds the 3-colour claudepix movement animations into docs/bench/stock_anims.js
 * so the bench can re-skin them (fetch() of JSON fails under file://, and the bench
 * must open from disk). Multi-palette animations (work coding, the DJ set) are
 * skipped: their extra palette indices collide with the ECHO skin's.
 *
 * Usage: node tools/stock_to_bench.js
 */
const fs = require('fs');
const path = require('path');
const IN = path.join(__dirname, 'claudepix_data');
const OUT = path.join(__dirname, '..', 'docs', 'bench', 'stock_anims.js');

const index = JSON.parse(fs.readFileSync(path.join(IN, '_index.json'), 'utf8'));
const out = {};
for (const e of index) {
  const key = e.filename.replace('.html', '');
  const d = JSON.parse(fs.readFileSync(path.join(IN, key + '.json'), 'utf8'));
  if (d.palette.length > 3) continue;
  // rows as strings: 20 chars each, keeps the file small and diffable
  out[key] = { name: d.name, palette: d.palette, frames: d.frames.map(f => ({ hold: f.hold, rows: f.grid.map(r => r.join('')) })) };
}
const body = '// Generated by tools/stock_to_bench.js from tools/claudepix_data (claudepix, 20x20).\n' +
  '// 3-colour movements only. Do not edit by hand.\n' +
  '(function(root){ root.STOCK_ANIMS = ' + JSON.stringify(out) + ';\n' +
  '  if (typeof module !== "undefined" && module.exports) module.exports = root.STOCK_ANIMS; })(typeof window !== "undefined" ? window : globalThis);\n';
fs.writeFileSync(OUT, body);
console.log(`embedded ${Object.keys(out).length} animations: ${Object.keys(out).join(', ')} -> ${OUT} (${(body.length/1024).toFixed(0)} KB)`);
